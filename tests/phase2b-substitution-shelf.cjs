const assert=require('node:assert/strict'),fs=require('node:fs'),ts=require('typescript');
require.extensions['.ts']=(m,file)=>m._compile(ts.transpileModule(fs.readFileSync(file,'utf8'),{fileName:file,compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,file);
const {newProject,validateProject,uid}=require('../src/core/model.ts');
const {DocumentStore}=require('../src/core/history.ts');
const {saveSubstitution,applySubstitution,renameSubstitution,deleteSubstitution,substitutionItems}=require('../src/animation/substitutions.ts');
const {addDrawingFrame,selectDrawingFrame,enableIndependentLayers,setLayerHoldEnd,frameList,isLayerHeld}=require('../src/animation/timeline.ts');
const stroke=(id,x=0)=>({id,kind:'stroke',tool:'brush',color:'#204b7b',points:[{x,y:0,p:1},{x:x+20,y:20,p:1}],size:4,opacity:1,pressure:false,response:1});
let p=newProject('mouth animation',640,360),layerId=p.activeLayerId;
const base=[stroke(uid(),10),stroke(uid(),30),stroke(uid(),50)];
p={...p,layers:p.layers.map(l=>l.id===layerId?{...l,operations:base}:l)};
// Capture two selected strokes, never modifying the source array.
const source=p.layers.find(l=>l.id===layerId).operations;
p=saveSubstitution(p,'Mouth A','mouth',[base[0].id,base[2].id]);
assert.equal(substitutionItems(p)[0].operations.length,2);assert.equal(p.layers.find(l=>l.id===layerId).operations,source);
assert.equal(substitutionItems(p)[0].name,'Mouth A');
const shelfId=substitutionItems(p)[0].id;
p=renameSubstitution(p,shelfId,'Mouth B');assert.equal(substitutionItems(p)[0].name,'Mouth B');
validateProject(JSON.parse(JSON.stringify(p)));
p=addDrawingFrame(p);p=addDrawingFrame(p);
const frames=frameList(p);assert.equal(frames.length,3);
p=selectDrawingFrame(p,frames[0].id);p=enableIndependentLayers(p);p=setLayerHoldEnd(p,layerId,frames[0].id,2);
assert(isLayerHeld(p,layerId,frames[1].id));
p=selectDrawingFrame(p,frames[1].id);
const heldBefore=p.layers.find(l=>l.id===layerId).operations;
const store=new DocumentStore(p);
const applied=applySubstitution(p,shelfId,'replace');
store.commit(applied,'Apply mouth');
assert(!isLayerHeld(applied,layerId,frames[1].id),'Must split held cel before writing');
const inserted=applied.layers.find(l=>l.id===layerId).operations;
assert.equal(inserted.length,2);assert.notEqual(inserted[0].id,base[0].id,'Copied strokes get fresh IDs');
assert.equal(frameList(applied)[0].drawings[layerId],source,'Original key preserved');
assert.equal(heldBefore,source,'Held source is unchanged');
assert.equal(substitutionItems(applied)[0].operations[0].id,base[0].id,'Shelf is not overwritten by applying');
validateProject(JSON.parse(JSON.stringify(applied)));
store.undo();assert(isLayerHeld(store.getSnapshot(),layerId,frames[1].id),'Undo restores hold');store.redo();assert.equal(store.getSnapshot().layers.find(l=>l.id===layerId).operations.length,2,'Redo restores inserted image');
p=applySubstitution(applied,shelfId,'append');assert.equal(p.layers.find(l=>l.id===layerId).operations.length,4);assert.notEqual(p.layers.find(l=>l.id===layerId).operations[0].id,p.layers.find(l=>l.id===layerId).operations[2].id);
let deleted=deleteSubstitution(p,shelfId);assert.equal(substitutionItems(deleted).length,0);assert.equal(deleted.layers.find(l=>l.id===layerId).operations.length,4,'Deleting shelf item never deletes placed art');validateProject(JSON.parse(JSON.stringify(deleted)));
assert.throws(()=>saveSubstitution(p,'','mouth'),/name/i);assert.throws(()=>saveSubstitution(p,'test','not-a-category'),/category/i);
let locked={...p,layers:p.layers.map(l=>l.id===layerId?{...l,locked:true}:l)};
assert.throws(()=>applySubstitution(locked,shelfId),/unlocked/i);
let vectorMismatch={...p,layers:p.layers.map(l=>l.id===layerId?{...l,kind:'vector',operations:[]}:l)};
assert.throws(()=>applySubstitution(vectorMismatch,shelfId),/raster\/vector/);
assert.throws(()=>validateProject({...p,substitutionShelf:{version:1,items:[{...substitutionItems(p)[0],id:'bad',operations:[{kind:'fill',id:'a',png:'javascript:bad'}]}]}}),/fill/i);
console.log('PASS substitutions: selection capture, named shelf, independent stroke IDs, saved JSON, held-cel split, append/replace, Undo/Redo, missing/locked/kind guards and safe removal');
