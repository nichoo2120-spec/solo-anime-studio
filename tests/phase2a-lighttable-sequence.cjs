const assert=require('node:assert/strict'),fs=require('node:fs'),ts=require('typescript');
require.extensions['.ts']=(m,file)=>m._compile(ts.transpileModule(fs.readFileSync(file,'utf8').replaceAll('import.meta.url',"'file:///sequence-test'").replaceAll('import.meta.env.DEV','false'),{fileName:file,compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,file);
const {newProject,validateProject}=require('../src/core/model.ts');
const {addDrawingFrame,setDrawingFrameHold,selectDrawingFrame,frameList}=require('../src/animation/timeline.ts');
const {sanitizeLightTablePins,toggleLightTablePin}=require('../src/animation/lightTable.ts');
const {sequencePlan,sequenceFrameName,sequenceSnapshot,zipStore,crc32}=require('../src/animation/sequenceExport.ts');
const {OnionSkinOverlay}=require('../src/engine/OnionSkinOverlay.ts');
(async()=>{
let p=newProject('Phase2A test',320,180);
p=addDrawingFrame(p);p=addDrawingFrame(p);
const ids=frameList(p).map(f=>f.id);
assert.equal(ids.length,3);
p=selectDrawingFrame(p,ids[0]);p=setDrawingFrameHold(p,2);
p=selectDrawingFrame(p,ids[1]);p=setDrawingFrameHold(p,3);
p=selectDrawingFrame(p,ids[2]);p=setDrawingFrameHold(p,1);
validateProject(JSON.parse(JSON.stringify(p)));
assert.deepEqual(sequencePlan(p).map(x=>x.celIndex),[0,0,1,1,1,2]);
assert.deepEqual(sequencePlan(p,true).map(x=>x.celIndex),[0,1,2]);
assert.equal(sequenceFrameName(10,100),'frame_0010.png');
assert.equal(sequenceSnapshot(p,1).animation,undefined);
assert.equal(sequenceSnapshot(p,1).layers[0].operations,frameList(p)[1].drawings[p.layers[0].id]);
assert.equal(sequenceSnapshot(p,1).layers[0].id,p.layers[0].id);
let pins=sanitizeLightTablePins(p,[{frameId:'stale',opacity:50},{frameId:ids[0],opacity:Infinity,dx:99999,dy:-99999,tint:'none'}]);
assert.equal(pins.length,1);assert.equal(pins[0].opacity,38);assert.equal(pins[0].dx,4096);assert.equal(pins[0].dy,-4096);
pins=toggleLightTablePin(p,pins,ids[1]);assert.equal(pins.length,2);
pins=toggleLightTablePin(p,pins,ids[0]);assert.deepEqual(pins.map(x=>x.frameId),[ids[1]]);
assert.equal(p.animation.frames.length,3,'Pins must not alter saved animation');
const overlay=Object.create(OnionSkinOverlay.prototype);
Object.assign(overlay,{project:p,settings:{enabled:false,previous:false,next:false,previousOpacity:0,nextOpacity:0,currentLayerOnly:true},pins:[],neighbors:[],ghosts:new Map(),generation:0,signature:'',paint(){},schedule(){},cancelTask(){},disposed:false});
overlay.setPins(pins);
assert.equal(overlay.neighbors.length,1);assert.equal(overlay.neighbors[0].frame.id,ids[1]);assert.equal(overlay.neighbors[0].kind,'pin');
// Pinning current frame must not create a self-ghost.
overlay.setPins(toggleLightTablePin(p,pins,ids[2]));assert.equal(overlay.neighbors.length,1);
const a=new Uint8Array([10,20,30,40]),b=new Uint8Array([1,2]);
assert.equal(crc32(a),crc32(new Uint8Array(a)));
const zip=zipStore([{name:'frame_0001.png',bytes:a},{name:'frame_0002.png',bytes:a},{name:'sequence-info.txt',bytes:b}]);
fs.writeFileSync('/tmp/phase2a-test.zip',Buffer.from(await zip.arrayBuffer()));
assert.equal(zip.type,'application/zip');
console.log('PASS Phase2A: holds, unique cels, numbering, source snapshots, pin sanitation, active pin exclusion and archive CRC.');
})().catch(e=>{console.error(e);process.exitCode=1;});
